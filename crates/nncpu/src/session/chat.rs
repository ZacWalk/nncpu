/// The tokens of one chat turn after `context`, the conversation so far: the
/// system prompt on the first turn, or on later ones the end of a reply left
/// open; then the user's `message` in the model's turn format, and the
/// opening of the reply. `thinking` lets a model that can reason do so.
pub(crate) fn turn_tokens(v: &Vocab, context: &[i32], system: &str, message: &str, thinking: bool) -> Vec<i32> {
    let first = context.is_empty();
    let think = thinking && v.can_think;
    let mut turn: Vec<i32> = Vec::new();
    let text = |turn: &mut Vec<i32>, t: &str| turn.extend(v.tokenize(t, false));
    let bos = |turn: &mut Vec<i32>| {
        if v.add_bos && v.bos_id >= 0 {
            turn.push(v.bos_id);
        }
    };
    let reply_closed = !first && context.last() == Some(&v.tok_turn_end);

    match v.chat {
        ChatFormat::Gemma => {
            // <start_of_turn>user\n{system\n\n}{message}<end_of_turn>\n<start_of_turn>model\n
            // Gemma has no system role; its template prepends the system text
            // to the first user turn. FunctionGemma gives it a turn of its
            // own: <start_of_turn>developer\n{system}<end_of_turn>\n.
            if first {
                bos(&mut turn);
                if v.developer_turn && !system.is_empty() {
                    turn.push(v.tok_turn_start);
                    text(&mut turn, "developer");
                    turn.push(v.tok_newline);
                    text(&mut turn, system);
                    turn.push(v.tok_turn_end);
                    turn.push(v.tok_newline);
                }
            } else {
                if !reply_closed {
                    turn.push(v.tok_turn_end);
                }
                turn.push(v.tok_newline);
            }
            turn.push(v.tok_turn_start);
            text(&mut turn, "user");
            turn.push(v.tok_newline);
            if first && !system.is_empty() && !v.developer_turn {
                text(&mut turn, &format!("{system}\n\n{message}"));
            } else {
                text(&mut turn, message);
            }
            turn.push(v.tok_turn_end);
            turn.push(v.tok_newline);
            turn.push(v.tok_turn_start);
            text(&mut turn, "model");
            turn.push(v.tok_newline);
        }
        ChatFormat::Gemma4 => {
            // [<|turn>system\n[<|think|>\n]{system}<turn|>\n]<|turn>user\n{message}<turn|>\n
            // <|turn>model\n[<|channel>thought\n<channel|>]
            // Gemma 4 has a system role, and <|think|> at the top of the
            // system turn lets the model think, so with thinking on there is a
            // system turn even without a system prompt. With thinking off, the
            // 26B and 31B templates also open the model turn with an empty
            // thought channel; without it those models start thinking on their
            // own.
            if first {
                bos(&mut turn);
                if !system.is_empty() || think {
                    turn.push(v.tok_turn_start);
                    text(&mut turn, "system");
                    turn.push(v.tok_newline);
                    if think {
                        turn.push(v.tok_think);
                        turn.push(v.tok_newline);
                    }
                    if !system.is_empty() {
                        text(&mut turn, system);
                    }
                    turn.push(v.tok_turn_end);
                    turn.push(v.tok_newline);
                }
            } else {
                if !reply_closed {
                    turn.push(v.tok_turn_end);
                }
                turn.push(v.tok_newline);
            }
            turn.push(v.tok_turn_start);
            text(&mut turn, "user");
            turn.push(v.tok_newline);
            text(&mut turn, message);
            turn.push(v.tok_turn_end);
            turn.push(v.tok_newline);
            turn.push(v.tok_turn_start);
            text(&mut turn, "model");
            turn.push(v.tok_newline);
            if v.empty_thought && !think {
                turn.push(v.tok_channel_start);
                text(&mut turn, "thought\n");
                turn.push(v.tok_channel_end);
            }
        }
        ChatFormat::Llama3 => {
            // <|start_header_id|>user<|end_header_id|>\n\n{message}<|eot_id|>
            // <|start_header_id|>assistant<|end_header_id|>\n\n
            if first {
                bos(&mut turn);
                if !system.is_empty() {
                    turn.push(v.tok_turn_start);
                    text(&mut turn, "system");
                    turn.push(v.tok_header_end);
                    text(&mut turn, &format!("\n\n{system}"));
                    turn.push(v.tok_turn_end);
                }
            } else if !reply_closed {
                turn.push(v.tok_turn_end);
            }
            turn.push(v.tok_turn_start);
            text(&mut turn, "user");
            turn.push(v.tok_header_end);
            text(&mut turn, &format!("\n\n{message}"));
            turn.push(v.tok_turn_end);
            turn.push(v.tok_turn_start);
            text(&mut turn, "assistant");
            turn.push(v.tok_header_end);
            text(&mut turn, "\n\n");
        }
        ChatFormat::ChatMl => {
            // [<|im_start|>system\n{system}<|im_end|>\n]<|im_start|>user\n{message}<|im_end|>\n
            // <|im_start|>assistant\n[<think>\n\n</think>\n\n | <think>\n]
            // Without a system prompt the template's own is used (Qwen2.5 has
            // one). With thinking on, the reply opens as the template opens it
            // then ("<think>\n", or as it is for Qwen3, which writes the
            // <think> itself), and Qwen3.8's system turn starts with the
            // instruction for its default reasoning effort. Each run of text
            // between markers is encoded whole, as llama.cpp encodes the
            // rendered template.
            if first {
                bos(&mut turn);
                let mut sys = if system.is_empty() {
                    v.default_system.clone()
                } else {
                    system.to_string()
                };
                if think && !v.think_instructions.is_empty() {
                    sys = if sys.is_empty() {
                        v.think_instructions.clone()
                    } else {
                        format!("{}\n\n{sys}", v.think_instructions)
                    };
                }
                if !sys.is_empty() {
                    turn.push(v.tok_turn_start);
                    text(&mut turn, &format!("system\n{sys}"));
                    turn.push(v.tok_turn_end);
                    text(&mut turn, "\n");
                }
            } else {
                if !reply_closed {
                    turn.push(v.tok_turn_end);
                }
                text(&mut turn, "\n");
            }
            turn.push(v.tok_turn_start);
            text(&mut turn, &format!("user\n{message}"));
            turn.push(v.tok_turn_end);
            text(&mut turn, "\n");
            turn.push(v.tok_turn_start);
            let open = if think { &v.reply_open_think } else { &v.reply_open };
            text(&mut turn, &format!("assistant\n{open}"));
        }
        ChatFormat::None => {
            // No known turn format: the text goes in as it is, one line per turn.
            if first {
                bos(&mut turn);
                if system.is_empty() {
                    text(&mut turn, message);
                } else {
                    text(&mut turn, &format!("{system}\n\n{message}"));
                }
            } else {
                text(&mut turn, &format!("\n{message}"));
            }
        }
    }
    turn
}

fn trim(s: &str) -> &str {
    s.trim_matches([' ', '\t', '\r', '\n'])
}

