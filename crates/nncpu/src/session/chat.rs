/// Move the longest complete, valid UTF-8 prefix of `pending` to the end of
/// `out`, writing U+FFFD for each byte sequence that cannot form a character
/// (the maximal-subpart rule decoders use). A character cut off by the end of
/// `pending` stays there to be completed by later bytes; with `fin` it
/// becomes U+FFFD instead.
pub(crate) fn utf8_take(pending: &mut Vec<u8>, out: &mut Vec<u8>, fin: bool) {
    const REPLACEMENT: &[u8] = "\u{FFFD}".as_bytes();
    let n = pending.len();
    let mut i = 0;
    while i < n {
        let c = pending[i];
        // Length from the lead byte, and the range of the second byte, per
        // RFC 3629: no overlong forms, surrogates or code points past U+10FFFF.
        let (len, lo, hi) = match c {
            0x00..=0x7F => (1, 0x80, 0xBF),
            0xC2..=0xDF => (2, 0x80, 0xBF),
            0xE0 => (3, 0xA0, 0xBF),
            0xED => (3, 0x80, 0x9F),
            0xE1..=0xEF => (3, 0x80, 0xBF),
            0xF0 => (4, 0x90, 0xBF),
            0xF4 => (4, 0x80, 0x8F),
            0xF1..=0xF3 => (4, 0x80, 0xBF),
            _ => (0, 0, 0),
        };
        if len == 0 {
            out.extend_from_slice(REPLACEMENT);
            i += 1;
            continue;
        }
        let mut k = 1;
        let mut broken = false;
        while k < len && i + k < n {
            let b = pending[i + k];
            let (lo, hi) = if k == 1 { (lo, hi) } else { (0x80, 0xBF) };
            if b < lo || b > hi {
                broken = true;
                break;
            }
            k += 1;
        }
        if k == len {
            out.extend_from_slice(&pending[i..i + len]);
        } else if !broken && !fin {
            break; // the rest of this character has not arrived yet
        } else {
            out.extend_from_slice(REPLACEMENT);
        }
        i += k;
    }
    pending.drain(..i);
}

/// Generated text, as it is produced: whole UTF-8 characters of the answer,
/// or of the model's reasoning (for a model that reasons before it answers).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Piece<'a> {
    /// Part of the answer.
    Text(&'a str),
    /// Part of the reasoning, without the markers around it.
    Thinking(&'a str),
}

/// Streams generated bytes to the callback as valid UTF-8 in whole
/// characters. The start of a character that has not fully arrived waits in
/// `pending` (the session's text_pending or thought_pending).
pub(crate) struct TextStream {
    thinking: bool,
    /// The callback asked to stop; it is not called again.
    stopped: bool,
    ready: Vec<u8>,
}

impl TextStream {
    pub fn new(thinking: bool) -> Self {
        TextStream {
            thinking,
            stopped: false,
            ready: Vec::new(),
        }
    }

    /// False once the callback has asked to stop.
    pub fn write(
        &mut self,
        pending: &mut Vec<u8>,
        piece: &[u8],
        fin: bool,
        on_piece: &mut dyn FnMut(Piece<'_>) -> bool,
    ) -> bool {
        if self.stopped {
            return false;
        }
        pending.extend_from_slice(piece);
        self.ready.clear();
        utf8_take(pending, &mut self.ready, fin);
        if !self.ready.is_empty() {
            let text = String::from_utf8_lossy(&self.ready);
            let p = if self.thinking {
                Piece::Thinking(&text)
            } else {
                Piece::Text(&text)
            };
            if !on_piece(p) {
                self.stopped = true;
            }
        }
        !self.stopped
    }
}

/// Tells a reply's reasoning from its answer, token by token, by the model's
/// thought markers (Vocab::tok_thought_open / close). The markers show
/// nowhere, and neither do the name line that opens a Gemma 4 thought channel
/// or the newlines that open the reasoning and the answer after it.
#[derive(Clone, Debug, Default)]
pub(crate) struct ThoughtSplit {
    open: i32,
    close: i32,
    /// A channel name line follows `open`.
    label: bool,
    /// In the reasoning.
    pub inside: bool,
    /// Dropping the channel name line.
    skip_line: bool,
    /// Dropping the newlines that open the reasoning or the answer.
    trim: bool,
}

impl ThoughtSplit {
    /// Carry on from the end of `context`: inside the reasoning when the last
    /// marker in the current turn opened it.
    pub fn start(v: &Vocab, context: &[i32]) -> ThoughtSplit {
        let mut s = ThoughtSplit {
            open: v.tok_thought_open,
            close: v.tok_thought_close,
            label: v.thought_label,
            ..ThoughtSplit::default()
        };
        if s.open < 0 || s.close < 0 {
            return s;
        }
        // Back to the current turn's last marker, then forward over what has
        // been shown since, for a name line or newlines still to be dropped.
        let mut at = context.len();
        while at > 0 {
            let t = context[at - 1];
            if t == s.open || t == s.close {
                break;
            }
            if t == v.tok_turn_start {
                return s;
            }
            at -= 1;
        }
        if at == 0 {
            return s;
        }
        let mut shown = Vec::new();
        for &t in &context[at - 1..] {
            s.route(t, v.piece(t), &mut shown);
        }
        s
    }

    /// Whether `token` belongs to the reasoning; `text` gets the part of its
    /// `piece` to show.
    pub fn route(&mut self, token: i32, piece: &[u8], text: &mut Vec<u8>) -> bool {
        text.clear();
        if self.open >= 0 && token == self.open {
            self.inside = true;
            self.skip_line = self.label;
            self.trim = true;
            return true;
        }
        if self.close >= 0 && token == self.close {
            let reasoning = self.inside;
            self.inside = false;
            self.skip_line = false;
            self.trim = true;
            return reasoning;
        }
        let mut i = 0;
        if self.inside && self.skip_line {
            let Some(nl) = piece.iter().position(|&b| b == b'\n') else {
                return true;
            };
            self.skip_line = false;
            i = nl + 1;
        }
        if self.trim {
            while i < piece.len() && (piece[i] == b'\n' || piece[i] == b'\r') {
                i += 1;
            }
            if i < piece.len() {
                self.trim = false;
            }
        }
        text.extend_from_slice(&piece[i..]);
        self.inside
    }
}

