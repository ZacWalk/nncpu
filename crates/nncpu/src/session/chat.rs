    use crate::tokenizer::TOKEN_CONTROL;
    use crate::tokenizer::tests::{CHATML_SPECIALS, GEMMA4_SPECIALS, QWEN38_TEMPLATE, load_ascii_vocab};

    /// Tokens as the template would write them: control tokens by name.
    fn render(v: &Vocab, ids: &[i32]) -> String {
        let mut s = Vec::new();
        for &id in ids {
            if v.types[id as usize] == TOKEN_CONTROL {
                s.extend_from_slice(v.tokens[id as usize].as_bytes());
            } else {
                s.extend_from_slice(v.piece(id));
            }
        }
        String::from_utf8(s).unwrap()
    }

    const QWEN3_TEMPLATE: &str = concat!(
        r"{%- if add_generation_prompt %}{{- '<|im_start|>assistant\n' }}{%- if enable_thinking is defined and ",
        r"enable_thinking is false %}{{- '<think>\n\n</think>\n\n' }}{%- endif %}{%- endif %}"
    );
    const GEMMA4_TEMPLATE: &str = r"{%- if enable_thinking -%}{{- '<|think|>\n' -}}{%- endif -%}";

    // Chat turns with thinking on and off, as the templates write them:
    // Qwen3.8's reasoning instruction heads the system turn and the reply
    // opens with "<think>\n" (Qwen3's with nothing); Gemma 4's <|think|> heads
    // a system turn, written for it alone if need be, and replaces the empty
    // thought channel of the 26B and 31B templates.
    #[test]
    fn chat_turn_thinking() {
        let q38 = load_ascii_vocab(CHATML_SPECIALS, true, QWEN38_TEMPLATE);
        let q3 = load_ascii_vocab(CHATML_SPECIALS, true, QWEN3_TEMPLATE);
        let g4 = load_ascii_vocab(GEMMA4_SPECIALS, false, GEMMA4_TEMPLATE);
        let g26 = load_ascii_vocab(
            GEMMA4_SPECIALS,
            false,
            &format!("{GEMMA4_TEMPLATE}{{{{- '<|channel>thought\\n<channel|>' -}}}}"),
        );
        assert!(q38.can_think && q3.can_think && g4.can_think && g26.can_think);
        assert!(!g4.empty_thought && g26.empty_thought);
        assert_eq!(g4.chat, ChatFormat::Gemma4);
        assert!(g4.thought_label && g4.tok_thought_open == g4.tok_channel_start);

        let turn = |v: &Vocab, system: &str, think: bool| render(v, &turn_tokens(v, &[], system, "Hi", think));
        let first = turn_tokens(&q38, &[], "Be helpful.", "Hi", true);
        let mut context = first.clone();
        context.extend(q38.tokenize("Ok", false));
        context.push(q38.tok_turn_end);
        assert_eq!(
            render(&q38, &first),
            "<|im_start|>system\nThink hard.\nThen answer.\n\nBe helpful.<|im_end|>\n<|im_start|>user\nHi\
             <|im_end|>\n<|im_start|>assistant\n<think>\n"
        );
        assert_eq!(
            turn(&q38, "", true),
            "<|im_start|>system\nThink hard.\nThen answer.<|im_end|>\n<|im_start|>user\nHi<|im_end|>\n\
             <|im_start|>assistant\n<think>\n"
        );
        assert_eq!(
            turn(&q38, "Be helpful.", false),
            "<|im_start|>system\nBe helpful.<|im_end|>\n<|im_start|>user\nHi<|im_end|>\n<|im_start|>assistant\n\
             <think>\n\n</think>\n\n"
        );
        assert_eq!(
            render(&q38, &turn_tokens(&q38, &context, "Be helpful.", "More", true)),
            "\n<|im_start|>user\nMore<|im_end|>\n<|im_start|>assistant\n<think>\n"
        );
        assert_eq!(
            turn(&q3, "", true),
            "<|im_start|>user\nHi<|im_end|>\n<|im_start|>assistant\n"
        );
        assert_eq!(
            turn(&q3, "", false),
            "<|im_start|>user\nHi<|im_end|>\n<|im_start|>assistant\n<think>\n\n</think>\n\n"
        );
        assert_eq!(
            turn(&g4, "Be helpful.", true),
            "<|turn>system\n<|think|>\nBe helpful.<turn|>\n<|turn>user\nHi<turn|>\n<|turn>model\n"
        );
        assert_eq!(
            turn(&g4, "", true),
            "<|turn>system\n<|think|>\n<turn|>\n<|turn>user\nHi<turn|>\n<|turn>model\n"
        );
        assert_eq!(turn(&g4, "", false), "<|turn>user\nHi<turn|>\n<|turn>model\n");
        assert_eq!(
            turn(&g26, "", false),
            "<|turn>user\nHi<turn|>\n<|turn>model\n<|channel>thought\n<channel|>"
        );
        assert_eq!(
            turn(&g26, "", true),
            "<|turn>system\n<|think|>\n<turn|>\n<|turn>user\nHi<turn|>\n<|turn>model\n"
        );
    }

    /// The reasoning shown, the answer shown, and how many tokens were
    /// reasoning, when `reply` follows `context`.
    fn run_split(v: &Vocab, context: &[i32], reply: &[i32]) -> (String, String, usize) {
        let mut split = ThoughtSplit::start(v, context);
        let (mut thought, mut answer, mut n) = (Vec::new(), Vec::new(), 0);
        let mut shown = Vec::new();
        for &t in reply {
            let reasoning = split.route(t, v.piece(t), &mut shown);
            if reasoning {
                thought.extend_from_slice(&shown);
                n += 1;
            } else {
                answer.extend_from_slice(&shown);
            }
        }
        (
            String::from_utf8(thought).unwrap(),
            String::from_utf8(answer).unwrap(),
            n,
        )
    }

    /// Text runs and marker tokens (Err(id)), as token ids.
    fn ids(v: &Vocab, parts: &[Result<&str, i32>]) -> Vec<i32> {
        parts
            .iter()
            .flat_map(|p| match p {
                Ok(text) => v.tokenize(text, false),
                Err(id) => vec![*id],
            })
            .collect()
    }

    // A reply's reasoning and answer are told apart by the thought markers,
    // which show nowhere, as do a Gemma 4 channel's name line and the
    // newlines that open the reasoning and the answer. A call that carries on
    // picks up where the context left off, within the current turn.
    #[test]
    fn thought_split() {
        let q = load_ascii_vocab(CHATML_SPECIALS, true, QWEN38_TEMPLATE);
        let g = load_ascii_vocab(GEMMA4_SPECIALS, false, GEMMA4_TEMPLATE);

        // Qwen: the prompt opened the reasoning; "Plan\n" is 5 tokens.
        let qp = turn_tokens(&q, &[], "", "Hi", true);
        let a = run_split(
            &q,
            &qp,
            &ids(&q, &[Ok("Plan\n"), Err(q.tok_thought_close), Ok("\n\nDone")]),
        );
        assert_eq!(a, ("Plan\n".into(), "Done".into(), 6));
        // Gemma 4: the model opens its thought channel and names it.
        let gp = turn_tokens(&g, &[], "", "Hi", true);
        let reply = ids(
            &g,
            &[
                Err(g.tok_thought_open),
                Ok("thought"),
                Err(g.tok_newline),
                Ok("Why"),
                Err(g.tok_newline),
                Err(g.tok_thought_close),
                Ok("Sky"),
            ],
        );
        assert_eq!(run_split(&g, &gp, &reply), ("Why\n".into(), "Sky".into(), 14));
        // Carrying on in the middle of the channel's name.
        let mut gc = gp.clone();
        gc.extend(ids(&g, &[Err(g.tok_thought_open), Ok("tho")]));
        let c = run_split(&g, &gc, &ids(&g, &[Ok("ught"), Err(g.tok_newline), Ok("X")]));
        assert_eq!((c.0.as_str(), c.1.as_str()), ("X", ""));
        // Thinking off: after the empty block, the answer's opening newline goes.
        let d = run_split(&q, &turn_tokens(&q, &[], "", "Hi", false), &ids(&q, &[Ok("\nA")]));
        assert_eq!((d.0.as_str(), d.1.as_str()), ("", "A"));
        // A reasoning block left open in an earlier turn does not reach this one.
        let mut qc = qp.clone();
        qc.extend(ids(
            &q,
            &[
                Ok("x"),
                Err(q.tok_turn_end),
                Ok("\n"),
                Err(q.tok_turn_start),
                Ok("assistant\n"),
            ],
        ));
        let e = run_split(&q, &qc, &ids(&q, &[Ok("B")]));
        assert_eq!((e.0.as_str(), e.1.as_str()), ("", "B"));
    }
